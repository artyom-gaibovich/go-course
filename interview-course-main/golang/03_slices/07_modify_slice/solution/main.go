package main

import "fmt"

type person struct {
	age int
}

func main() {
	// Создаем слайс с len=2, cap=2 (базовый массив [person{0}, person{0}])
	people := make([]person, 2)

	// p1 получает указатель на элемент people[1] в текущем базовом массиве
	p1 := &people[1]
	fmt.Printf("%p\n", p1) // Адрес элемента в исходном массиве

	// Увеличиваем age через указатель: people[1].age становится 1
	p1.age++

	// append добавляет 3 элемента к слайсу len=2, cap=2.
	// Нужен capacity 2+3=5, но есть только 2, поэтому происходит реаллокация.
	// Go создает новый массив большего размера (обычно удваивает: cap=4),
	// копирует туда старые данные [person{0}, person{1}],
	// добавляет новые элементы.
	// Переменная people теперь указывает на НОВЫЙ массив.
	people = append(people, person{}, person{}, person{})

	// cap будет >= 5, обычно Go выделяет больше (например, 6 или 8)
	fmt.Println(cap(people)) // Зависит от реализации, обычно 6

	// p1 все еще указывает на СТАРЫЙ массив, который больше не используется.
	// Увеличиваем age в старом массиве: старый people[1].age становится 2
	p1.age++

	// people[1].age читается из НОВОГО массива, где age = 1 (скопирован при реаллокации)
	fmt.Println(people[1].age) // Выведет: 1

	// p1.age читается из СТАРОГО массива, где age = 2
	fmt.Println(p1.age) // Выведет: 2
}

// Ответ:
// <адрес в памяти>
// 6 (или другое значение >= 5, зависит от реализации)
// 1
// 2
//
// Объяснение:
//
// 1. Исходное состояние:
//    people := make([]person, 2) создает слайс len=2, cap=2
//    Базовый массив: [person{age:0}, person{age:0}]
//
// 2. p1 := &people[1]:
//    p1 получает указатель на people[1] в текущем базовом массиве
//    Это АДРЕС в памяти конкретного элемента массива
//
// 3. p1.age++ (первый раз):
//    Изменяет age элемента в исходном массиве: [person{0}, person{1}]
//
// 4. people = append(people, person{}, person{}, person{}):
//    - Текущий cap=2, нужен cap >= 5
//    - Происходит реаллокация: создается новый массив
//    - Старые данные копируются в новый массив
//    - people теперь указывает на новый массив
//    - ВАЖНО: p1 продолжает указывать на старый массив!
//
// 5. p1.age++ (второй раз):
//    Изменяет age в СТАРОМ массиве, который больше не связан с people
//    Старый массив: [person{0}, person{2}]
//
// 6. people[1].age:
//    Читает из НОВОГО массива, где age был скопирован как 1
//    Выводит: 1
//
// 7. p1.age:
//    Читает из СТАРОГО массива, где age был увеличен дважды
//    Выводит: 2
//
// Ключевые моменты:
//
// - Указатель на элемент слайса хранит адрес в базовом массиве
// - append может создать новый базовый массив при реаллокации
// - Старые указатели продолжают указывать на старый массив
// - После реаллокации слайс и указатель больше не связаны
// - Это потенциальный источник багов: dangling pointers
//
// Правила безопасности:
//
// - Не храните указатели на элементы слайса долгосрочно
// - Если слайс может измениться (append), указатели инвалидируются
// - Используйте индексы вместо указателей, если слайс изменяется
// - Или убедитесь, что слайс имеет достаточный capacity заранее
//
// Capacity при реаллокации до версии Go 1.18:
// Go удваивает capacity, пока len < 1024, потом растит на 25%.
// Для len=2, cap=2, после добавления 3 элементов, новый cap обычно 6.
//
// ============================================================================
// ДЕТАЛЬНОЕ ОБЪЯСНЕНИЕ: РЕАЛЛОКАЦИЯ СЛАЙСОВ В GO 1.25
// ============================================================================
//
// 1. ЧТО ТАКОЕ DANGLING POINTER (ВИСЯЧИЙ УКАЗАТЕЛЬ)
//
// Dangling pointer - это указатель, который ссылается на память, которая:
// - Была освобождена (freed)
// - Была переаллоцирована для других целей
// - Больше не содержит ожидаемые данные
// - Может быть перезаписана в любой момент
//
// В контексте Go слайсов:
// Когда происходит реаллокация слайса, старый базовый массив может:
// - Остаться в памяти до сборки мусора (если на него есть ссылки)
// - Быть собран GC (если ссылок нет)
// - Быть перезаписан другими данными
//
// Указатель на элемент старого массива становится "dangling":
//   p := &slice[0]      // Указатель на элемент базового массива
//   slice = append(...) // Может создать новый массив
//   *p = 42             // ОПАСНО: модифицируем старый массив!
//
// Диаграмма dangling pointer:
//   До реаллокации:
//   ┌─────────────────┐
//   │ Old Array       │
//   │ [0][1][2][3]    │
//   └─────────────────┘
//        ↑       ↑
//        │       └─── p (указатель)
//        └─────────── slice.array
//
//   После реаллокации:
//   ┌─────────────────┐          ┌──────────────────────┐
//   │ Old Array       │          │ New Array            │
//   │ [0][1][2][3]    │          │ [0][1][2][3][4][5]   │
//   └─────────────────┘          └──────────────────────┘
//        ↑                            ↑
//        │                            └─── slice.array
//        └─ p (dangling!)
//
// Проблемы dangling pointers:
// 1. Чтение устаревших данных (как в нашем примере)
// 2. Изменение памяти, которая больше не связана со слайсом
// 3. Потенциальные segmentation fault (в других языках)
// 4. Data races, если другие горутины используют новый массив
//
// 2. АЛГОРИТМ РЕАЛЛОКАЦИИ В GO 1.25
//
// Когда len + добавляемые элементы > cap, Go выделяет новый массив.
// Размер нового массива вычисляется по формуле (runtime/slice.go):
//
// Алгоритм growslice (Go 1.25):
//   if newLen <= doublecap:
//       newcap = doublecap
//   else:
//       while:
//           newcap += (newcap + 3*threshold) >> 2
//           if newcap >= newLen:
//               break
//
// Где:
// - newLen = требуемая длина (len + добавляемые элементы)
// - doublecap = старый cap * 2
// - threshold = 256
//
// Упрощенная логика:
// - Если нужно <= 2*cap: удваиваем capacity
// - Если нужно > 2*cap: растим итеративно на ~25% от текущего
//
// После вычисления логического capacity, Go выравнивает по размеру:
// - Округляет вверх до ближайшего размера класса памяти
// - Это объясняет, почему cap может быть больше минимально необходимого
//
// 3. КОНКРЕТНЫЕ ПРИМЕРЫ РЕАЛЛОКАЦИИ
//
// ПРИМЕР 1: Слайс из 4 элементов, добавляем 2
// ────────────────────────────────────────────
//   Начальное состояние:
//     slice := []int{1, 2, 3, 4}  // len=4, cap=4
//
//   Операция: slice = append(slice, 5, 6)
//   Требуется: newLen = 4 + 2 = 6
//   Старый cap: 4
//   doublecap: 4 * 2 = 8
//
//   Логика: newLen (6) <= doublecap (8)
//   Результат: newcap = 8
//
//   Итог: новый массив с cap=8
//   Память:
//     Старый: [1][2][3][4]          (cap=4, может быть GC)
//     Новый:  [1][2][3][4][5][6][][]  (cap=8, len=6)
//
//   Если p := &slice[0] до append:
//     p указывает на старый массив [1][2][3][4]
//     slice[0] читает из нового массива [1][...]
//     *p и slice[0] - ЭТО РАЗНЫЕ ЯЧЕЙКИ ПАМЯТИ!
//
// ПРИМЕР 2: Слайс из 4 элементов, добавляем 100
// ────────────────────────────────────────────
//   Начальное состояние:
//     slice := make([]int, 4, 4)  // len=4, cap=4
//
//   Операция: slice = append(slice, make([]int, 100)...)
//   Требуется: newLen = 4 + 100 = 104
//   Старый cap: 4
//   doublecap: 4 * 2 = 8
//
//   Логика: newLen (104) > doublecap (8)
//   Итеративный рост:
//     Итерация 1: cap = 8
//     Итерация 2: cap = 8 + (8 + 768) >> 2 = 8 + 194 = 202
//     202 >= 104, стоп
//
//   Результат: newcap ≈ 202 (может быть округлен до 208 или 224)
//
//   Память:
//     Старый: [][][][][] (4 элемента)
//     Новый:  [............................] (104+ элемента, cap ≈ 202+)
//
//   Коэффициент роста: 202 / 4 = 50.5x
//
// ПРИМЕР 3: Постепенное добавление (по одному элементу)
// ────────────────────────────────────────────
//   slice := make([]int, 0, 4)
//
//   append 1 элемент: len=1, cap=4 (без реаллокации)
//   append 1 элемент: len=2, cap=4 (без реаллокации)
//   append 1 элемент: len=3, cap=4 (без реаллокации)
//   append 1 элемент: len=4, cap=4 (без реаллокации)
//   append 1 элемент: len=5, newLen=5, doublecap=8
//                     → реаллокация, новый cap=8
//
//   История capacity: 4 → 8 → 16 → 32 → 64 → 128 → 256 → ...
//   (удвоение до len=256, потом рост ~25%)
//
// ПРИМЕР 4: Большой единовременный append
// ────────────────────────────────────────────
//   slice := []int{1, 2}  // len=2, cap=2
//
//   Добавляем 1000 элементов:
//   slice = append(slice, make([]int, 1000)...)
//   newLen = 2 + 1000 = 1002
//   doublecap = 2 * 2 = 4
//
//   newLen (1002) >> doublecap (4)
//   Итеративный рост начинается с cap=4:
//     cap = 4
//     while cap < 1002:
//         cap += (cap + 768) >> 2
//   Финал: cap ≈ 1280 (зависит от memory class alignment)
//
//   Важно: Go выделил cap=1280 для newLen=1002
//   Резерв: 1280 - 1002 = 278 элементов
//
// 4. КОГДА УКАЗАТЕЛИ СТАНОВЯТСЯ DANGLING
//
// Указатель инвалидируется при реаллокации:
//
//   slice := []int{1, 2, 3, 4}
//   p := &slice[0]              // p указывает на базовый массив
//
//   // Сценарий А: реаллокация НЕ происходит
//   slice = append(slice[:2], 5) // len=3, cap=4, без реаллокации
//   *p // OK: читаем из того же массива
//
//   // Сценарий Б: реаллокация происходит
//   slice = append(slice, 6, 7, 8, 9) // len=7, нужна реаллокация
//   *p // DANGLING: читаем из старого массива!
//
// Как определить, произошла ли реаллокация:
//
//   oldCap := cap(slice)
//   slice = append(slice, elements...)
//   if cap(slice) != oldCap {
//       // Произошла реаллокация, все старые указатели недействительны
//   }
//
// Более надежный способ (через unsafe):
//
//   import "unsafe"
//   oldPtr := unsafe.Pointer(&slice[0])
//   slice = append(slice, elements...)
//   newPtr := unsafe.Pointer(&slice[0])
//   if oldPtr != newPtr {
//       // Реаллокация произошла
//   }
//
// 5. КАК ИЗБЕЖАТЬ ПРОБЛЕМ С DANGLING POINTERS
//
// Стратегия 1: Не храните указатели на элементы слайса
//   // Плохо:
//   p := &slice[5]
//   slice = append(slice, x)
//   p.field = value // Может быть dangling
//
//   // Хорошо:
//   index := 5
//   slice = append(slice, x)
//   slice[index].field = value
//
// Стратегия 2: Предаллоцируйте capacity
//   // Если знаете максимальный размер:
//   slice := make([]T, 0, maxSize)
//   // Теперь append не вызовет реаллокацию, если len <= maxSize
//   p := &slice[0] // Безопасно, пока не превышаем capacity
//
// Стратегия 3: Не используйте append, если есть указатели
//   slice := make([]T, fixedSize)
//   p := &slice[0]
//   // Не вызываем append, только прямое присваивание
//   slice[1] = value // OK
//
// Стратегия 4: Возвращайте значения, а не указатели
//   // Вместо:
//   func getFirst(slice []T) *T { return &slice[0] }
//
//   // Используйте:
//   func getFirst(slice []T) T { return slice[0] }
//
// Стратегия 5: Явно копируйте данные
//   // Если нужен независимый объект:
//   original := slice[i]
//   copy := original // Копия структуры
//   slice = append(slice, x)
//   // Работаем с copy, а не с &slice[i]
//
// 6. ПРИМЕР БАГА С DANGLING POINTER В РЕАЛЬНОМ КОДЕ
//
// type User struct { Name string }
//
// func processUsers() {
//     users := []User{{"Alice"}, {"Bob"}}
//     currentUser := &users[0] // Запомнили указатель
//
//     // Где-то в другой функции:
//     users = append(users, User{"Charlie"}, User{"Dave"})
//     // Если произошла реаллокация, currentUser теперь dangling!
//
//     currentUser.Name = "Alicia" // Модифицируем СТАРЫЙ массив
//     fmt.Println(users[0].Name)  // Выведет "Alice", а не "Alicia"!
// }
//
// 7. ЗАЩИТА ОТ DANGLING POINTERS НА УРОВНЕ RUNTIME
//
// Go Runtime НЕ защищает от dangling pointers к элементам слайсов:
// - GC не собирает старый массив, пока на него есть ссылки
// - Но нет проверок, что указатель ещё валиден для слайса
// - Нет segmentation fault (как в C), но логические баги
//
// В отличие от C/C++:
// - В Go старый массив остается доступен (пока есть ссылки)
// - Нет undefined behavior с доступом к freed memory
// - Но данные могут быть устаревшими (как в нашем примере)
//
// 8. ПРАКТИЧЕСКИЕ ВЫВОДЫ
//
// - Реаллокация создает НОВЫЙ массив, старые указатели недействительны
// - Go 1.25 удваивает capacity до ~256 элементов, потом растит на ~25%
// - Dangling pointer в Go = указатель на старый массив после реаллокации
// - Используйте индексы вместо указателей для динамических слайсов
// - Предаллоцируйте capacity, если размер известен заранее
// - Проверяйте изменение capacity, если критично отслеживать реаллокацию
//
// 9. СРАВНЕНИЕ С ДРУГИМИ ЯЗЫКАМИ
//
// C++:
//   std::vector<T> vec = {1, 2, 3, 4};
//   int* p = &vec[0];
//   vec.push_back(5); // Может инвалидировать указатели
//   *p = 10;          // Undefined behavior если была реаллокация!
//
// Rust:
//   let mut vec = vec![1, 2, 3, 4];
//   let p = &vec[0];        // Заимствуем ссылку
//   vec.push(5);            // ОШИБКА КОМПИЛЯЦИИ: cannot borrow as mutable
//   // Rust запрещает изменять vec, пока существует ссылка!
//
// Go:
//   slice := []int{1, 2, 3, 4}
//   p := &slice[0]
//   slice = append(slice, 5) // Компилируется, но p может быть dangling
//   *p = 10                  // Модифицирует старый массив, НЕ slice[0]
//
// Go находится посередине: нет защиты Rust, но и нет UB C++.
