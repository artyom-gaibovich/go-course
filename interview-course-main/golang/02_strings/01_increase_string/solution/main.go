package main

import (
	"fmt"
	"strings"
	"time"
)

func main() {
	start := time.Now()
	makeString()
	fmt.Println(time.Since(start))
}

// Проблема: конкатенация строк через += создает новую строку при каждой итерации.
// Строки в Go неизменяемы, поэтому каждая операция str += создает новую строку,
// копируя все предыдущие символы. Это приводит к O(n²) сложности.

// Решение: использовать strings.Builder для эффективной конкатенации.
func makeString() string {
	var builder strings.Builder
	// Предварительно резервируем память для повышения производительности.
	builder.Grow(100_000 * 10) // примерная оценка размера

	for i := 0; i < 100_000; i++ {
		builder.WriteString(fmt.Sprintf("%d", i))
	}
	return builder.String()
}

