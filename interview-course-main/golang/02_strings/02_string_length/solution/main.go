package main

import (
	"fmt"
	"unicode/utf8"
)

func main() {
	str := "ddЯЙ異"
	fmt.Println("Длина через len:", len(str))
	fmt.Println("Длина через RuneCountInString:", utf8.RuneCountInString(str))
}

// Ответ:
// Длина через len: 9
// Длина через RuneCountInString: 5
//
// Объяснение:
// 1. len(str) возвращает длину строки в байтах, а не количество символов.
// 2. Строка "ddЯЙ異" содержит:
//    - 'd' (1 байт) × 2 = 2 байта
//    - 'Я' (2 байта в UTF-8) = 2 байта
//    - 'Й' (2 байта в UTF-8) = 2 байта
//    - '異' (3 байта в UTF-8) = 3 байта
//    Итого: 2 + 2 + 2 + 3 = 9 байт
//
// 3. utf8.RuneCountInString возвращает количество Unicode символов (рун).
//    В строке 5 символов: d, d, Я, Й, 異
//
// 4. В Go строки хранятся как последовательность байт в UTF-8 кодировке.
//    Для работы с символами нужно использовать функции из пакета unicode/utf8
//    или итерироваться через строку как через руны: for _, r := range str
