//
//    if avgLatency1 <= avgLatency2 {
//        return server1
//    }
//
// 3. P2C на основе CPU:
//    Метрика: текущая загрузка CPU
//
//    if cpuUsage1 <= cpuUsage2 {
//        return server1
//    }
//
// 4. Взвешенный P2C:
//    Метрика: комбинация нескольких факторов
//
//    score = 0.5*connections + 0.3*latency + 0.2*cpuUsage
//    if score1 <= score2 {
//        return server1
//    }
