//
// ============================================================================
// Распределенный rate limiting
// ============================================================================
//
// Для распределенных систем:
//
// 1. Redis с INCR и EXPIRE:
//    key = "rate_limit:{user_id}:{timestamp_bucket}"
//    INCR key
//    EXPIRE key 1
//    if INCR result > rps: reject
//
// 2. Redis с Lua script для атомарности:
//    local count = redis.call('INCR', KEYS[1])
//    if count == 1 then
//        redis.call('EXPIRE', KEYS[1], 1)
//    end
//    return count
//
// 3. Распределенный Token Bucket:
//    - Центральное хранилище токенов в Redis
//    - Периодическое пополнение через scheduler
//
// 4. Consensus-based (Raft/Paxos):
//    - Для критичных систем с строгими гарантиями
//    - Высокая latency, сложная реализация

//
// ============================================================================
// ЧТО ТАКОЕ BURSTS И КАК С НИМИ РАБОТАТЬ
// ============================================================================
//
// BURST (всплеск) — это кратковременное превышение среднего RPS.
// Вместо равномерного потока запросов, приходит большое количество за короткий промежуток.
//
// ПРИМЕРЫ BURSTS В РЕАЛЬНЫХ СИСТЕМАХ:
//
// 1. Пользовательский интерфейс:
//    Пользователь кликает кнопку "Обновить" несколько раз подряд.
//
//    Временная шкала:
//    00:00.000 - click! (request 1)
//    00:00.100 - click! (request 2)
//    00:00.200 - click! (request 3)
//    00:00.300 - click! (request 4)
//    00:00.400 - click! (request 5)
//    ...тишина до 00:10...
//
//    За первые 500ms пришло 5 запросов (10 RPS локально),
//    но средний RPS за 10 секунд = 0.5 RPS.
//
// 2. Scheduled Jobs:
//    Cron задачи запускаются в одно время.
//
//    00:00:00 - 1000 серверов начинают backup
//    00:00:01 - все 1000 отправляют статистику в центральный сервис
//    Burst: 1000 запросов в секунду
//    Остальные 59 секунд: 0 запросов
//
// 3. Cache Miss Storm:
//    Популярный cache key истекает, множество запросов одновременно обращаются к БД.
//
//    Нормально: cache hit, 0 запросов к БД
//    Cache истек: 100 одновременных запросов → 100 запросов к БД
//    Burst: 100x нормальной нагрузки
//
// 4. Mobile App Launch:
//    Пользователь открывает приложение → 10+ API запросов за 1 секунду.
//
//    Launch sequence:
//    - GET /api/user/profile
//    - GET /api/notifications
//    - GET /api/feed
//    - GET /api/settings
//    - GET /api/friends
//    ... всего 10 запросов за 500ms
//
// 5. Retry Storm:
//    Сервис был недоступен, клиенты делали retry, все успешно переподключились.
//
//    Нормально: 100 RPS
//    После восстановления: 500 RPS (100 live + 400 retries)
//    Burst: 5x нормальной нагрузки
//
// КАК РАЗНЫЕ АЛГОРИТМЫ ОБРАБАТЫВАЮТ BURSTS:
//
// Сценарий: RPS limit = 10, пришло 15 запросов за первые 100ms, потом тишина.
//
// Алгоритм 1: Sliding Window (строгий, без bursts)
//   Запросы 1-10: ✅ разрешены
//   Запросы 11-15: ❌ отклонены (лимит 10/сек достигнут)
//   Результат: точное соблюдение лимита, но bursts блокируются
//
// Алгоритм 2: Token Bucket (позволяет малые bursts)
//   Изначально: 10 токенов в bucket
//   Запросы 1-10: ✅ разрешены (токены израсходованы)
//   Запросы 11-15: ❌ отклонены (токенов нет)
//   Но! Если bucket_capacity = 20:
//     Запросы 1-20: ✅ разрешены (burst до 20)
//     Запросы 21-15: ❌ отклонены
//   Результат: контролируемые bursts до размера bucket
//
// Алгоритм 3: Fixed Window (позволяет большие bursts)
//   Окно 1: [00:00:00 - 00:01:00], лимит 10
//   00:00:59: приходит 10 запросов → ✅ разрешены
//   00:01:00: новое окно, счетчик сбрасывается
//   00:01:01: приходит 10 запросов → ✅ разрешены
//   Итого: 20 запросов за 2 секунды (10 RPS вместо лимита!)
//   Результат: burst в 2x на границе окон
//
// НАСТРОЙКА TOKEN BUCKET ДЛЯ BURSTS:
//
// Параметры Token Bucket:
// - refillRate: сколько токенов добавляется в секунду (= RPS limit)
// - maxTokens (capacity): максимум токенов в bucket
//
// Размер capacity определяет допустимый burst:
//
// Пример 1: Строгий limiter (без bursts)
//   refillRate = 100 токенов/сек
//   capacity = 100 токенов
//   Burst: максимум 100 запросов за раз
//
// Пример 2: Терпимый к bursts
//   refillRate = 100 токенов/сек
//   capacity = 200 токенов
//   Burst: максимум 200 запросов за раз (2x лимита)
//
//   Временная шкала:
//   00:00 - bucket полон (200 токенов)
//   00:00 - burst 200 запросов → bucket пуст
//   00:01 - добавилось 100 токенов (refill)
//   00:01 - можем обработать еще 100 запросов
//
// Пример 3: Очень терпимый (большие bursts)
//   refillRate = 100 токенов/сек
//   capacity = 1000 токенов
//   Burst: до 1000 запросов за раз (10x лимита!)
//
//   Use case: накопление "кредита" в периоды низкой нагрузки
//
// ПРАКТИЧЕСКИЕ РЕКОМЕНДАЦИИ:
//
// 1. Выбор capacity для Token Bucket:
//
//    Формула: capacity = refillRate × burst_duration_seconds
//
//    Примеры:
//    - refillRate=100, burst=2 сек → capacity=200
//    - refillRate=1000, burst=0.5 сек → capacity=500
//
// 2. Когда разрешать bursts:
//    ✅ UI приложения (пользователь кликает несколько раз)
//    ✅ Batch операции (загрузка данных при старте)
//    ✅ Retry after failure (временный всплеск после восстановления)
//    ❌ DDoS защита (bursts опасны)
//    ❌ Database rate limiting (bursts могут перегрузить БД)
//
// 3. Мониторинг bursts:
//    Метрики:
//    - burst_size: максимальное количество запросов в короткий промежуток
//    - burst_frequency: как часто происходят bursts
//    - rejected_during_burst: сколько запросов отклонено во время burst
//
// 4. Graceful degradation:
//    Вместо жесткого reject, можно:
//    - Очередь запросов (queue)
//    - Задержка (throttle)
//    - Приоритизация (важные запросы первыми)
//
// ============================================================================
// АЛГОРИТМ P2C (POWER OF TWO CHOICES)
// ============================================================================
//
// P2C — это алгоритм балансировки нагрузки, который выбирает наименее загруженный
// из ДВУХ случайно выбранных серверов.
//
// ПРИНЦИП РАБОТЫ:
//
// Простая балансировка (Round Robin):
//   request 1 → server 1
//   request 2 → server 2
//   request 3 → server 3
//   request 4 → server 1 (цикл)
//   Проблема: не учитывает нагрузку серверов
//
// Полный перебор (Least Loaded):
//   request → выбрать сервер с минимальной нагрузкой из ВСЕХ N серверов
//   Сложность: O(N) для каждого запроса
//   Проблема: медленно для большого N
//
// Power of Two Choices (P2C):
//   1. Случайно выбираем ДВА сервера из N
//   2. Отправляем запрос на сервер с МЕНЬШЕЙ нагрузкой из этих двух
//   Сложность: O(2) = O(1) (константа!)
//
// МАТЕМАТИКА ПОЧЕМУ ЭТО РАБОТАЕТ:
//
// Теорема: Выбор лучшего из 2 случайных серверов экспоненциально лучше,
//          чем выбор 1 случайного сервера.
//
// Симуляция с 10 серверами, 1000 запросов:
//
// Random (1 сервер):
//   Максимальная нагрузка: ~150 запросов
//   Разброс: ±50% от среднего
//
// P2C (лучший из 2):
//   Максимальная нагрузка: ~110 запросов
//   Разброс: ±10% от среднего
//
// Least Loaded (все N):
//   Максимальная нагрузка: ~101 запрос
//   Разброс: ±1% от среднего
//
// Вывод: P2C достигает ~90% эффективности Least Loaded при O(1) сложности!
//
// ПРИМЕНЕНИЕ P2C В RATE LIMITING:
//
// Проблема: Распределенный rate limiter с несколькими инстансами.
// Нужно выбрать, на какой инстанс отправить проверку лимита.
//
// Архитектура:
//   API Gateway → выбирает Rate Limiter инстанс → проверяет лимит
//                    ↓
//   [RL Instance 1] (нагрузка: 100 RPS)
//   [RL Instance 2] (нагрузка: 50 RPS)
//   [RL Instance 3] (нагрузка: 200 RPS)
//
// С P2C:
//   1. Gateway случайно выбирает Instance 1 и Instance 3
//   2. Сравнивает нагрузку: 100 vs 200
//   3. Выбирает Instance 1 (меньше нагружен)
//   4. Отправляет запрос на Instance 1
//
// ВАРИАНТЫ P2C:
//
// 1. P2C на основе активных соединений:
//    Метрика: количество текущих запросов в обработке
