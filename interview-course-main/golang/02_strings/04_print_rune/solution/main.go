package main

import "fmt"

func main() {
	// Демонстрация неизменяемости строк
	s := "test"

	// s[0] возвращает байт (тип byte, он же uint8), а не руну.
	// Для строки "test" это символ 't' с ASCII кодом 116.
	println(s[0]) // Выведет: 116

	// Эта строка НЕ СКОМПИЛИРУЕТСЯ!
	// Ошибка: cannot assign to s[0] (neither addressable nor a map index expression)
	// Строки в Go неизменяемые (immutable).
	// s[0] = 'R'

	// Правильное решение: преобразовать строку в []rune, изменить, вернуть.
	s1 := []rune(s)

	// s1[0] теперь имеет тип rune (он же int32), можно изменять.
	fmt.Println(s1[0]) // Выведет: 116 (код символа 't')

	// Меняем первую руну на 'R'
	s1[0] = 'R'

	// s1 — это слайс рун, при печати выводится как числа.
	fmt.Println(s1) // Выведет: [82 101 115 116]

	// Преобразуем обратно в строку для корректного вывода.
	fmt.Printf("%s\n", string(s1)) // Выведет: Rest
}

// Ответ:
// Код НЕ СКОМПИЛИРУЕТСЯ из-за строки s[0] = 'R'
//
// Объяснение:
//
// 1. Строки в Go неизменяемые (immutable).
//    Попытка изменить байт строки приведет к ошибке компиляции:
//    "cannot assign to s[0]"
//
// 2. s[0] возвращает байт (byte), а не символ.
//    Для ASCII символов это работает, но для Unicode нужны руны.
//
// 3. Правильный способ изменить строку:
//    - Преобразовать в []rune (если нужна поддержка Unicode)
//    - Изменить нужные элементы
//    - Преобразовать обратно в string
//
// 4. Альтернативный способ через []byte (только для ASCII):
//    b := []byte(s)
//    b[0] = 'R'
//    s = string(b)
//
// 5. Разница byte vs rune:
//    - byte (uint8) — один байт, подходит для ASCII
//    - rune (int32) — кодовая точка Unicode, может быть многобайтовой
//
// Trade-offs:
// - []rune: безопасно для Unicode, но занимает больше памяти (4 байта на символ)
// - []byte: эффективнее по памяти, но работает только с ASCII или требует
//   ручной обработки UTF-8
