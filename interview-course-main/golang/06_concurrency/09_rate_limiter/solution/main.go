// СРАВНЕНИЕ АЛГОРИТМОВ БАЛАНСИРОВКИ:
//
// Алгоритм       | Сложность | Качество | Use Case
// ---------------|-----------|----------|----------------------------------
// Random         | O(1)      | Низкое   | Stateless, равные серверы
// Round Robin    | O(1)      | Среднее  | Равные серверы, предсказуемость
// P2C            | O(1)      | Высокое  | Большой парк серверов
// Least Loaded   | O(N)      | Отличное | Малый парк серверов (<10)
// Consistent Hash| O(log N)  | Среднее  | Sticky sessions, caching
//
// ПРИМЕРЫ ПРИМЕНЕНИЯ P2C:
//
// 1. Envoy Proxy:
//    Использует P2C для балансировки между upstream серверами.
//    Метрика: активные запросы.
//
// 2. gRPC Load Balancing:
//    Клиент выбирает из 2 серверов на основе latency.
//
// 3. Kubernetes Service Mesh:
//    Istio может использовать P2C для выбора pod'ов.
//
// 4. CDN Edge Selection:
//    Cloudflare выбирает edge сервер из 2 ближайших.
//
// ОПТИМИЗАЦИИ P2C:
//
// 1. Кеширование выбора:
//    Не пересчитывать для каждого запроса, кешировать на 100ms.
//
// 2. Weighted P2C:
//    Учитывать capacity серверов при выборе.
//
//    if load1/capacity1 <= load2/capacity2 {
//        return server1
//    }
//
// 3. Adaptive P2C:
//    Динамически изменять метрику в зависимости от ситуации.
//    - Нормальная нагрузка: connections
//    - Высокая нагрузка: latency
//    - Критическая: error rate
//
// 4. P2C с health checks:
//    Не выбирать unhealthy серверы.
//
//    do {
//        i1 = rand.Intn(n)
//        i2 = rand.Intn(n)
//    } while !healthy[i1] || !healthy[i2]
//
// КЛЮЧЕВЫЕ ВЫВОДЫ:
//
// - Bursts — кратковременное превышение среднего RPS
// - Token Bucket позволяет контролировать bursts через capacity
// - P2C выбирает лучший из 2 случайных серверов
// - P2C достигает ~90% эффективности Least Loaded при O(1)
// - P2C идеален для большого количества серверов (N > 10)
// - Метрику для P2C выбирать в зависимости от use case
// - Комбинация Token Bucket (bursts) + P2C (балансировка) = эффективный
//   распределенный rate limiter
