func testConcurrency() {
	limiter := NewRateLimiter(100)
	var wg sync.WaitGroup
	passed := 0
	var mu sync.Mutex

	// Запускаем 10 горутин, каждая делает 20 запросов
	for i := 0; i < 10; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for j := 0; j < 20; j++ {
				if limiter.Allow() {
					mu.Lock()
					passed++
					mu.Unlock()
				}
			}
		}()
	}

	wg.Wait()
	fmt.Printf("Конкурентный тест: Прошло %d из 200 запросов (лимит 100)\n", passed)
}

// Объяснение решений:
//
// ============================================================================
// Решение 1: Sliding Window Log
// ============================================================================
//
// Алгоритм:
// 1. Храним timestamp каждого запроса за последнюю секунду
// 2. При новом запросе удаляем timestamp'ы старше 1 секунды
// 3. Проверяем, не превышено ли количество запросов (len < rps)
// 4. Если не превышено - добавляем текущий timestamp
//
// Плюсы:
// - Точное соблюдение лимита для любого скользящего окна
// - Нет burst'ов на границах временных окон
// - Простая логика
//
// Минусы:
// - Память O(rps) для хранения timestamp'ов
// - O(n) для очистки устаревших запросов
// - Не оптимально для очень высоких RPS (>100K)
//
// Сложность:
// - Время: O(n) где n = количество запросов за последнюю секунду
// - Память: O(rps)
//
// ============================================================================
// Решение 2: Token Bucket
// ============================================================================
//
// Алгоритм:
// 1. Bucket содержит токены (изначально = capacity = rps)
// 2. Каждый запрос расходует 1 токен
// 3. Токены пополняются с постоянной скоростью (rps токенов/сек)
// 4. Если токенов нет - запрос отклоняется
//
// Плюсы:
// - Очень эффективно: O(1) время, O(1) память
// - Позволяет небольшие burst'ы
// - Стандартный алгоритм в индустрии
//
// Минусы:
// - Менее точное соблюдение лимита (позволяет burst до capacity)
// - Требует точной настройки refill rate
//
// Использование:
// - AWS API Gateway, Nginx rate limiting
// - Подходит для большинства реальных систем
//
// ============================================================================
// Решение 3: Fixed Window Counter
// ============================================================================
//
// Алгоритм:
// 1. Разбиваем время на фиксированные окна по 1 секунде
// 2. Считаем запросы в текущем окне
// 3. Если превышен лимит - отклоняем
// 4. При начале нового окна - сбрасываем счетчик
//
// Плюсы:
// - Самое быстрое: O(1) время, O(1) память
// - Минимальная нагрузка на CPU
// - Простейшая реализация
//
// Минусы:
// - Проблема burst'ов на границах окон
// - Может пропустить до 2×rps запросов за секунду
// - Наименее точное решение
//
// Пример проблемы:
// RPS = 100, окно = [0:00:00 - 0:00:01)
// 0:00:00.9 - пришло 100 запросов (OK)
// 0:00:01.0 - новое окно, счетчик сброшен
// 0:00:01.1 - пришло 100 запросов (OK)
// Итого: 200 запросов за 0.2 секунды!
//
// ============================================================================
// Сравнение решений
// ============================================================================
//
// Критерий             | Sliding Window | Token Bucket | Fixed Window
// ---------------------|----------------|--------------|-------------
// Точность             | Высокая        | Средняя      | Низкая
// Память               | O(rps)         | O(1)         | O(1)
// Время                | O(n)           | O(1)         | O(1)
// Burst'ы              | Нет            | Да (малые)   | Да (большие)
// Сложность реализации | Средняя        | Средняя      | Низкая
// Использование в prod | Средне         | Часто        | Редко
//
