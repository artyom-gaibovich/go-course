package main

import "fmt"

type User struct {
	Name string
}

func main() {
	user := User{Name: "Гриша"}
	fmt.Println("Имя до обновления:", user.Name)

	updateUser(user)
	fmt.Println("Имя после обновления:", user.Name)
}

// updateUser принимает структуру User по значению (копия).
func updateUser(u User) {
	// Изменение u.Name влияет только на локальную копию структуры.
	u.Name = "Таненбаум"
	fmt.Println("Имя внутри функции [updateUser]:", u.Name)

	// Передаем указатель на локальную копию u.
	resetUser(&u)
	// После вызова resetUser локальная копия u не изменилась,
	// так как resetUser изменил сам указатель, а не значение по нему.
	fmt.Println("Имя после вызова [resetUser] внутри функции [updateUser]:", u.Name)
}

// resetUser принимает указатель на User.
func resetUser(u *User) {
	// ВАЖНО: здесь мы меняем сам указатель u, а не значение по указателю.
	// u теперь указывает на новую структуру, но это не влияет на оригинальную переменную.
	u = &User{Name: "Безымянный"}
	fmt.Println("Имя внутри функции [resetUser]:", u.Name)
}

// Ответ:
// Имя до обновления: Гриша
// Имя внутри функции [updateUser]: Таненбаум
// Имя внутри функции [resetUser]: Безымянный
// Имя после вызова [resetUser] внутри функции [updateUser]: Таненбаум
// Имя после обновления: Гриша
//
// Объяснение:
// 1. updateUser принимает User по значению, создается копия структуры.
// 2. Изменение u.Name в updateUser влияет только на копию, оригинальная структура не меняется.
// 3. resetUser получает указатель на локальную копию u из updateUser.
// 4. В resetUser мы переназначаем указатель u на новую структуру, но это не влияет
//    ни на локальную копию в updateUser, ни на оригинальную переменную user в main.
// 5. Чтобы изменить значение по указателю, нужно использовать *u = User{...},
//    а не u = &User{...}.
