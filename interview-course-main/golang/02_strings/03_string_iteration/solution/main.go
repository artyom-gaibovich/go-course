package main

import "fmt"

func main() {
	str := "G😀o"
	for i := 0; i < len(str); i++ {
		fmt.Printf("%c ", str[i])
	}
}

// Ответ:
// G � � o
//
// Объяснение:
// 1. Итерация через строку по индексам (str[i]) дает доступ к отдельным байтам.
// 2. Строка "G😀o" в UTF-8:
//    - 'G' = 1 байт (0x47)
//    - '😀' = 4 байта (0xF0 0x9F 0x98 0x80)
//    - 'o' = 1 байт (0x6F)
// 3. При выводе str[1], str[2], str[3], str[4] мы получаем отдельные байты эмодзи,
//    которые не являются валидными UTF-8 символами по отдельности, поэтому выводятся как �.
