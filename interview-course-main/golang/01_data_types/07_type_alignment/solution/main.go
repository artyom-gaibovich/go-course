package main

import (
	"fmt"
	"unsafe"
)

type Foo struct {
	aaa bool  // 1 байт
	bbb int32 // 4 байта
	ccc bool  // 1 байт
}

type Bar struct {
	aaa bool  // 1 байт
	ccc bool  // 1 байт
	bbb int32 // 4 байта
}

func main() {
	ff := Foo{}
	bb := Bar{}

	// unsafe.Sizeof возвращает размер типа в байтах с учетом выравнивания.
	fmt.Println(unsafe.Sizeof(ff)) // Выведет: 12
	fmt.Println(unsafe.Sizeof(bb)) // Выведет: 8
}

// Ответ: 12 и 8
//
// Объяснение:
//
// Go автоматически добавляет padding (выравнивание) между полями структуры
// для оптимизации доступа к памяти. Каждый тип должен быть выровнен
// по границе, кратной его размеру (alignment requirement).
//
// Правила выравнивания:
// - bool: размер 1 байт, выравнивание 1 байт
// - int32: размер 4 байта, выравнивание 4 байта
//
// Структура Foo:
// [aaa: bool][padding: 3 байта][bbb: int32][ccc: bool][padding: 3 байта]
//  0          1-3                4-7         8          9-11
//
// 1. aaa (bool) занимает 1 байт (offset 0)
// 2. bbb (int32) требует выравнивания по 4 байтам, поэтому добавляется
//    3 байта padding после aaa, bbb начинается с offset 4
// 3. ccc (bool) занимает 1 байт (offset 8)
// 4. Вся структура выравнивается по самому строгому требованию (int32 = 4),
//    поэтому добавляется 3 байта padding в конце
// Итого: 1 + 3 + 4 + 1 + 3 = 12 байт
//
// Структура Bar:
// [aaa: bool][ccc: bool][padding: 2 байта][bbb: int32]
//  0          1          2-3                4-7
//
// 1. aaa (bool) занимает 1 байт (offset 0)
// 2. ccc (bool) занимает 1 байт (offset 1)
// 3. bbb (int32) требует выравнивания по 4 байтам, поэтому добавляется
//    2 байта padding, bbb начинается с offset 4
// Итого: 1 + 1 + 2 + 4 = 8 байт
//
// Вывод:
// Порядок полей в структуре влияет на её размер в памяти из-за padding.
// Группировка полей одинакового размера уменьшает общий размер структуры.
// Для минимизации размера структуры располагайте поля от большего к меньшему
// или группируйте поля одинакового размера вместе.
