package main

import "fmt"

type X struct {
	Val int
}

func main() {
	test()
}

// S — метод с value receiver (получает копию структуры).
func (x X) S() {
	fmt.Println(x.Val)
}

func test() {
	x := X{10}

	// defer захватывает аргументы в момент вызова, а не выполнения.
	// Так как S() имеет value receiver, структура x копируется СЕЙЧАС.
	// Копия сохраняет Val = 10.
	defer x.S()

	// Это изменение влияет только на оригинальную переменную x.
	// Отложенный вызов работает с копией, захваченной ранее.
	x.Val = 256
}

// Ответ: программа выведет 10
//
// Объяснение:
// 1. defer вычисляет аргументы в момент вызова defer, а не выполнения.
// 2. Метод S() имеет value receiver (x X), значит при вызове метода
//    структура копируется.
// 3. Копия создается в момент выполнения строки defer x.S(),
//    когда x.Val = 10.
// 4. Последующее изменение x.Val = 256 не влияет на копию.
// 5. При выходе из функции отложенный вызов работает с копией,
//    где Val = 10.
//
// Если бы S() был с pointer receiver: func (x *X) S(),
// то вывод был бы 256, так как defer захватил бы указатель на x.
