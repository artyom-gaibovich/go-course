// 1. Итерация по map в Go имеет случайный порядок.
//    Это ЗАДУМАНО разработчиками языка, а не баг.
//
// 2. История:
//    - В Go 1.0 порядок был более предсказуемым (зависел от хеш-функции)
//    - Разработчики заметили, что программисты полагаются на порядок
//    - С Go 1.0+ порядок НАМЕРЕННО рандомизируется при каждом запуске
//    - Это помогает находить баги, связанные с предположением о порядке
//
// 3. Реализация рандомизации:
//    - При создании map Go инициализирует случайное начальное значение (seed)
//    - Порядок итерации начинается со случайного bucket в хеш-таблице
//    - Внутри bucket порядок также рандомизируется
//
// 4. Почему рандомизация полезна:
//    - Выявляет скрытые зависимости от порядка элементов
//    - Предотвращает написание недетерминированного кода
//    - Защищает от hash collision атак (DoS)
//    - Заставляет явно сортировать, когда нужен порядок
//
// 4.1. ЧТО ТАКОЕ HASH COLLISION DOS АТАКИ
//
// Hash Collision DoS (Denial of Service) — атака, использующая слабость
// хеш-функций для создания большого числа коллизий, что приводит к:
// - Деградации производительности map с O(1) до O(n)
// - Зависанию приложения
// - Отказу в обслуживании легитимных пользователей
//
// КАК РАБОТАЕТ АТАКА:
//
// Шаг 1: Изучение хеш-функции
// Атакующий анализирует хеш-функцию, используемую в map.
// Если функция детерминирована (одинаковый вход → одинаковый хеш),
// можно предсказать, какие ключи попадут в один bucket.
//
// Шаг 2: Генерация коллизий
// Атакующий создает набор ключей, которые все дают одинаковый хеш:
//   hash("key1") = 42
//   hash("key2") = 42
//   hash("key3") = 42
//   ...
//   hash("keyN") = 42  (N может быть 100000+)
//
// Шаг 3: Отправка вредоносных данных
// Атакующий отправляет запрос с этими ключами, например:
//   POST /api/data
//   {"key1": "val1", "key2": "val2", ..., "keyN": "valN"}
//
// Шаг 4: Деградация производительности
// Сервер парсит JSON в map[string]interface{}:
//   myMap := make(map[string]interface{})
//   for k, v := range jsonData {
//       myMap[k] = v  // ВСЕ ключи попадают в ОДИН bucket!
//   }
//
// Результат:
// - Вставка: O(1) → O(n) из-за длинной цепочки коллизий
// - Поиск: O(1) → O(n) при обходе цепочки
// - 100000 вставок: из 0.1ms в 10+ секунд
// - CPU загружен на 100%, сервер не отвечает
//
// ИСТОРИЧЕСКИЕ ПРИМЕРЫ:
//
// 1. Атака 28C3 (2011):
//    Исследователи продемонстрировали коллизии для:
//    - PHP (array)
//    - Python (dict)
//    - Ruby (Hash)
//    - Java (HashMap)
//    Один HTTP POST с 65K ключами заставлял сервер зависать на минуты.
//
// 2. CVE-2011-4815 (Ruby):
//    Атака на веб-приложения Ruby on Rails через параметры HTTP POST.
//    Атакующий мог отправить запрос с коллизиями и вызвать DoS.
//
// 3. CVE-2011-4885 (Tomcat/JBoss):
//    Java-серверы были уязвимы для атаки через параметры формы.
//    Сервер тратил O(n²) времени на обработку запроса.
//
// КАК GO ЗАЩИЩАЕТСЯ ОТ HASH COLLISION DOS:
//
// Защита 1: Рандомизация хеш-функции (hash seed randomization)
// При создании map Go генерирует случайное начальное значение (seed):
//   m := make(map[string]int)  // seed = random()
//
// Хеш вычисляется как:
//   hash(key) = hash_function(key, seed)
//
// Разные запуски программы → разные seed → разные хеши:
//   Запуск 1: hash("attack_key", seed=123) = 42
//   Запуск 2: hash("attack_key", seed=789) = 951
//
// Атакующий НЕ может предсказать, какие ключи вызовут коллизии,
// так как seed неизвестен и меняется.
//
// Защита 2: Случайное начало итерации
// Go начинает итерацию range со случайного bucket, что:
// - Скрывает внутреннюю структуру map от атакующего
// - Не позволяет узнать порядок хранения ключей
// - Затрудняет reverse engineering хеш-функции
//
// Защита 3: Overflow buckets
// При большом числе коллизий Go создает overflow buckets,
// но из-за рандомизации это происходит равномерно, а не в одном месте.
//
// ПРИМЕР АТАКИ БЕЗ РАНДОМИЗАЦИИ:
//
// Представим, что Go использовал детерминированный хеш:
//   hash("aaa") = 1
//   hash("bbb") = 1
//   hash("ccc") = 1
//
// Атакующий отправляет:
//   POST /api/process
//   {"aaa": 1, "bbb": 2, "ccc": 3, ... (100000 ключей с hash=1)}
//
// Сервер:
//   m := make(map[string]int)
//   for k, v := range request.Form {
//       m[k] = v  // O(n) каждая вставка из-за коллизий!
//   }
//   // Итого: O(n²) для 100000 элементов
//
// С рандомизацией:
//   hash("aaa", seed=<random>) = ???  (непредсказуемо)
//   Атакующий не может подобрать ключи для коллизий.
//
// ПРАКТИЧЕСКИЕ РЕКОМЕНДАЦИИ:
