package main

import "fmt"

func main() {
	data := []int{10, 20, 30, 40}
	fmt.Println("Изначальный слайс:", data)

	modify(data[:2])
	fmt.Println("Слайс после изменений:", data)
}

// modify получает слайс data[:2], который имеет len=2, cap=4 (capacity исходного слайса).
func modify(slice []int) {
	// append добавляет элементы. Если capacity достаточен, элементы добавляются в тот же массив.
	// Здесь capacity=4, добавляем 2 элемента, итого нужно 4 элемента - capacity достаточен.
	// Элементы 50 и 60 записываются в позиции data[2] и data[3], перезаписывая 30 и 40.
	slice = append(slice, 50, 60)
	fmt.Println("Слайс в функции модификации:", slice)
}

// Ответ:
// Изначальный слайс: [10 20 30 40]
// Слайс в функции модификации: [10 20 50 60]
// Слайс после изменений: [10 20 50 60]
//
// Объяснение:
// 1. data[:2] создает слайс с len=2, cap=4, указывающий на тот же массив, что и data.
// 2. В modify мы делаем slice = append(slice, 50, 60).
//    Так как capacity достаточен (4 >= 2+2), элементы добавляются в тот же массив.
// 3. Элементы 50 и 60 записываются в позиции data[2] и data[3], перезаписывая 30 и 40.
// 4. append возвращает новый слайс с увеличенной длиной (len=4), но указывающий на тот же массив.
// 5. Исходный слайс data также указывает на тот же массив, поэтому изменения видны:
//    data[2] и data[3] теперь содержат 50 и 60 вместо 30 и 40.
// 6. len(data) остается 4, но содержимое массива изменилось.
//
// Важно: хотя append возвращает "новый" слайс, он может указывать на тот же массив,
// если capacity достаточен. В этом случае изменения в массиве видны через все слайсы,
// которые на него указывают.
