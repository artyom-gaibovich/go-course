/*
Домашнее задание 2: Таблица умножения

Выведи таблицу умножения от 1 до 9 в виде красиво отформатированной сетки.

Ожидаемый вид:
   1  2  3  4  5  6  7  8  9
   2  4  6  8 10 12 14 16 18
   3  6  9 12 15 18 21 24 27
   ...
   9 18 27 36 45 54 63 72 81

Требования:
  - Числа выровнены по правому краю (ширина колонки — 3 символа)
  - Используй вложенные циклы for
  - Подсказка по форматированию: fmt.Printf("%3d", n)

Усложнение (по желанию):
  Добавь заголовок строк и столбцов:
     ×  | 1  2  3  4  5  6  7  8  9
    ----+---------------------------
     1  | 1  2  3  ...
     2  | 2  4  6  ...
*/

package main

import "fmt"

func main() {
	// TODO: реализуй вывод таблицы умножения
	// Внешний цикл — строки (i от 1 до 9)
	// Внутренний цикл — столбцы (j от 1 до 9)
	for i := 1; i <= 9; i++ {
		for j := 1; j <= 9; j++ {
			fmt.Printf("%3d", i*j)
		}
		fmt.Println()
	}
}
