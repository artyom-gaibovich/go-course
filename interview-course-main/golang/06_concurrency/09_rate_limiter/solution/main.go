// ============================================================================
// Решение 1: Sliding Window Log (точное, но требует больше памяти)
// ============================================================================

type RateLimiter struct {
	mu       sync.Mutex    // Защита от конкурентного доступа
	rps      int           // Максимальное количество запросов в секунду
	requests []time.Time   // История запросов за последнюю секунду
	window   time.Duration // Временное окно (1 секунда)
}

// NewRateLimiter создает новый rate limiter с заданным RPS.
func NewRateLimiter(rps int) *RateLimiter {
	return &RateLimiter{
		rps:      rps,
		requests: make([]time.Time, 0, rps),
		window:   1 * time.Second,
	}
}

// Allow проверяет, можно ли пропустить запрос.
// Возвращает true если запрос в пределах лимита, false если лимит превышен.
func (rl *RateLimiter) Allow() bool {
	rl.mu.Lock()
	defer rl.mu.Unlock()

	now := time.Now()
	windowStart := now.Add(-rl.window)

	// Удаляем запросы старше 1 секунды.
	// Находим первый запрос, который попадает в окно.
	validStart := 0
	for i, reqTime := range rl.requests {
		if !reqTime.Before(windowStart) {
			validStart = i
			break
		}
	}

	// Обрезаем устаревшие запросы.
	rl.requests = rl.requests[validStart:]

	// Проверяем, не превышен ли лимит.
	if len(rl.requests) >= rl.rps {
		return false // Лимит превышен
	}

	// Добавляем текущий запрос в историю.
	rl.requests = append(rl.requests, now)
	return true
}

// ============================================================================
// Решение 2: Token Bucket (более эффективное, но чуть менее точное)
// ============================================================================

type TokenBucketLimiter struct {
	mu           sync.Mutex
	tokens       int           // Текущее количество токенов
	maxTokens    int           // Максимальное количество токенов (capacity)
	refillRate   int           // Скорость пополнения (токенов в секунду)
	lastRefill   time.Time     // Время последнего пополнения
	refillPeriod time.Duration // Период пополнения
}

// NewTokenBucketLimiter создает token bucket limiter.
func NewTokenBucketLimiter(rps int) *TokenBucketLimiter {
	return &TokenBucketLimiter{
		tokens:       rps,
		maxTokens:    rps,
		refillRate:   rps,
		lastRefill:   time.Now(),
		refillPeriod: 1 * time.Second,
	}
}

// Allow проверяет и расходует токен если доступен.
func (tbl *TokenBucketLimiter) Allow() bool {
	tbl.mu.Lock()
	defer tbl.mu.Unlock()

	// Пополняем токены на основе прошедшего времени.
	now := time.Now()
	elapsed := now.Sub(tbl.lastRefill)

	// Вычисляем количество новых токенов.
	newTokens := int(elapsed.Seconds() * float64(tbl.refillRate))
	if newTokens > 0 {
		tbl.tokens += newTokens
		if tbl.tokens > tbl.maxTokens {
			tbl.tokens = tbl.maxTokens
		}
		tbl.lastRefill = now
	}

	// Проверяем доступность токена.
	if tbl.tokens > 0 {
		tbl.tokens--
		return true
	}

	return false
}

// ============================================================================
// Решение 3: Fixed Window Counter (самое быстрое, но наименее точное)
// ============================================================================

type FixedWindowLimiter struct {
	mu          sync.Mutex
	rps         int
	counter     int
	windowStart time.Time
	window      time.Duration
}

// NewFixedWindowLimiter создает fixed window limiter.
func NewFixedWindowLimiter(rps int) *FixedWindowLimiter {
	return &FixedWindowLimiter{
		rps:         rps,
		counter:     0,
		windowStart: time.Now(),
		window:      1 * time.Second,
	}
}

// Allow проверяет лимит в текущем временном окне.
func (fwl *FixedWindowLimiter) Allow() bool {
	fwl.mu.Lock()
	defer fwl.mu.Unlock()

	now := time.Now()

	// Если текущее окно истекло, начинаем новое окно.
	if now.Sub(fwl.windowStart) >= fwl.window {
		fwl.windowStart = now
		fwl.counter = 0
	}

	// Проверяем лимит в текущем окне.
	if fwl.counter >= fwl.rps {
		return false
	}

	fwl.counter++
	return true
}

