package main

import (
	"fmt"
	"time"
)

func main() {
	ch := make(chan bool)
	go func() {
		time.Sleep(3 * time.Second)
		fmt.Println("Отдельная горутина отвисла")
		ch <- false
	}()

	ticker := time.NewTicker(time.Second)
	defer ticker.Stop() // Важно: останавливаем ticker для освобождения ресурсов

	for {
		select {
		case <-ticker.C:
			fmt.Println("Произошел тик тикера")
			// ПРОБЛЕМА: отправка в небуферизированный канал может заблокировать,
			// если нет получателя. Нужно использовать select с default или буферизированный канал.
			select {
			case ch <- true:
			default:
				// Пропускаем отправку, если канал занят
			}
		case value := <-ch:
			fmt.Printf("Получено значение %t\n", value)
			return
		}
	}
}

// Ответ (исходный код):
// Произошел тик тикера
// (зависание и паника)
//
// Проблемы:
// 1. ch <- true в select может заблокировать, если горутина еще не готова читать.
// 2. ticker не останавливается, что приводит к утечке ресурсов.
// 3. Нет обработки случая, когда канал занят.
//
// Решение:
// 1. Использовать вложенный select с default для неблокирующей отправки.
// 2. Остановить ticker при выходе из функции.
// 3. Альтернатива: использовать буферизированный канал make(chan bool, 1).
