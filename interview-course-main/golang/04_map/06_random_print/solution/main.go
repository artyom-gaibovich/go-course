package main

import (
	"fmt"
	"sort"
)

func main() {
	myMap := map[int]string{1: "a", 2: "b", 3: "c"}

	// Итерация по map в Go имеет СЛУЧАЙНЫЙ порядок.
	// Порядок вывода НЕ гарантируется и может меняться между запусками.
	fmt.Println("Случайный порядок:")
	for key, value := range myMap {
		fmt.Println("Key:", key, "Value:", value)
	}

	// Если нужен детерминированный порядок, отсортируйте ключи отдельно.
	fmt.Println("\nДетерминированный порядок:")
	keys := make([]int, 0, len(myMap))
	for k := range myMap {
		keys = append(keys, k)
	}
	sort.Ints(keys)
	for _, k := range keys {
		fmt.Println("Key:", k, "Value:", myMap[k])
	}
}

