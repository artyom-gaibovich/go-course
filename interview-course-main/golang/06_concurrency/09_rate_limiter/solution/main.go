func testLimiter(limiter *RateLimiter) {
	// Тест 1: Первые 10 запросов должны пройти
	passed := 0
	for i := 0; i < 10; i++ {
		if limiter.Allow() {
			passed++
		}
	}
	fmt.Printf("Тест 1: Прошло %d из 10 запросов (ожидается 10)\n", passed)

	// Тест 2: 11-й запрос должен быть отклонен
	if !limiter.Allow() {
		fmt.Println("Тест 2: 11-й запрос отклонен ✓")
	} else {
		fmt.Println("Тест 2: 11-й запрос прошел ✗")
	}

	// Тест 3: После ожидания 1 секунды лимит должен сброситься
	time.Sleep(1100 * time.Millisecond)
	passed = 0
	for i := 0; i < 10; i++ {
		if limiter.Allow() {
			passed++
		}
	}
	fmt.Printf("Тест 3: После ожидания прошло %d из 10 (ожидается 10)\n", passed)
}

