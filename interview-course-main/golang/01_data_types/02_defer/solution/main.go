package main

import "fmt"

func main() {
	x := 10
	y := 20

	// defer вычисляет аргументы в момент вызова defer, а не выполнения.
	// Здесь x передается как аргумент в анонимную функцию, поэтому
	// значение x копируется СЕЙЧАС (x = 10).
	defer func(val int) {
		fmt.Println("x:", val)
	}(x)

	// Здесь анонимная функция захватывает переменную y по ссылке (closure).
	// Значение y будет прочитано в момент выполнения defer, а не вызова.
	defer func() {
		fmt.Println("y:", y)
	}()

	// Изменения x и y не влияют на первый defer (x уже скопирован),
	// но влияют на второй defer (y читается при выполнении).
	x = 100
	y = 200

	fmt.Println("Конец main")
}

// Ответ:
// Конец main
// y: 200
// x: 10
//
// Объяснение:
// 1. defer выполняются в обратном порядке (LIFO - Last In First Out).
// 2. Первый defer захватывает значение x в момент вызова defer (x = 10).
// 3. Второй defer захватывает переменную y по ссылке, значение читается при выполнении (y = 200).
// 4. Порядок выполнения: сначала "Конец main", затем второй defer (y: 200), затем первый defer (x: 10).
