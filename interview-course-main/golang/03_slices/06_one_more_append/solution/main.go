package main

import "fmt"

func main() {
	// Создаем слайс с len=3, cap=3 на базе массива [1, 2, 3]
	nums := []int{1, 2, 3}

	// Передаем срез nums[0:2], то есть слайс с len=2, cap=3,
	// указывающий на тот же базовый массив.
	addNum(nums[0:2])
	fmt.Println(nums) // Выведет: [1 2 4]

	// Снова передаем срез nums[0:2], теперь базовый массив [1, 2, 4]
	addNums(nums[0:2])
	fmt.Println(nums) // Выведет: [1 2 4]
}

// addNum добавляет один элемент в слайс.
func addNum(nums []int) {
	// nums имеет len=2, cap=3 (cap остался от оригинального слайса).
	// append(nums, 4) добавляет 4 в позицию nums[2], так как cap достаточно.
	// Изменение происходит в базовом массиве, который разделяется с main.
	// НО: локальная переменная nums обновляется (len становится 3),
	// а в main оригинальный слайс nums не видит это изменение len.
	nums = append(nums, 4)
	// В базовом массиве теперь [1, 2, 4], но main все еще видит len=3
}

// addNums добавляет два элемента в слайс.
func addNums(nums []int) {
	// nums имеет len=2, cap=3 (но базовый массив уже [1, 2, 4]).
	// append(nums, 5, 6) пытается добавить 2 элемента.
	// len=2 + 2 = 4, но cap=3, поэтому нужна реаллокация.
	// Создается новый массив большего размера, данные копируются.
	// Локальная переменная nums теперь указывает на новый массив.
	// Изменения НЕ влияют на оригинальный массив в main.
	nums = append(nums, 5, 6)
	// Новый массив: [1, 2, 5, 6], но main его не видит
}

// Ответ:
// [1 2 4]
// [1 2 4]
//
// Объяснение:
//
// 1. Исходное состояние:
//    nums := []int{1, 2, 3}  // len=3, cap=3, базовый массив [1, 2, 3]
//
// 2. Первый вызов addNum(nums[0:2]):
//    - nums[0:2] создает срез len=2, cap=3, указывающий на тот же массив
//
//    ПОЧЕМУ cap=3, А НЕ 2?
//    Правило: при создании среза s[low:high] новый capacity вычисляется как:
//      new_cap = cap(s) - low
//
//    В нашем случае:
//      nums[0:2] -> new_cap = 3 - 0 = 3
//
//    Почему так? Потому что срез "видит" базовый массив от позиции low
//    до конца массива. Capacity - это расстояние от текущей позиции
//    до конца базового массива.
//
//    Визуализация:
//      nums =     [1][2][3]
//                  ↑     ↑
//               low=0  end
//      nums[0:2] может использовать элементы [0], [1], [2] -> cap=3
//
//    Если бы был nums[1:2]:
//      new_cap = 3 - 1 = 2
//      nums[1:2] может использовать только [1], [2] -> cap=2
//
//    - В addNum: append(nums, 4) добавляет 4 в позицию [2]
//    - Capacity достаточно (2+1 <= 3), реаллокации нет
//    - Базовый массив изменяется: [1, 2, 3] → [1, 2, 4]
//    - В main видны изменения базового массива: [1 2 4]
//    - НО: len оригинального слайса остался 3, а не изменился на 2+1
//
// 3. Второй вызов addNums(nums[0:2]):
//    - nums[0:2] создает срез len=2, cap=3 (снова cap = 3 - 0 = 3)
//    - Базовый массив теперь [1, 2, 4] (изменился после первого вызова)
//    - В addNums: append(nums, 5, 6) пытается добавить 2 элемента
//    - Нужен capacity 2+2=4, но есть только 3
//    - append создает новый массив большего размера (обычно удваивает)
//    - Копирует [1, 2] в новый массив, добавляет 5, 6
//    - Локальная переменная nums указывает на новый массив
//    - Оригинальный массив в main не изменяется
//    - В main: [1 2 4] (без изменений)
//
// 4. Ключевые моменты:
//    - Слайс = {ptr, len, cap} — это три поля, передаются по значению
//    - append может изменять базовый массив (если хватает cap)
//    - append может создать новый массив (если cap не хватает)
//    - Присваивание nums = append(...) меняет локальную переменную,
//      не оригинальный слайс в вызывающей функции
//    - Чтобы вернуть измененный слайс, нужно: return nums
//      или передавать указатель: func addNum(nums *[]int)
//
// 5. Правила работы с append:
//    - Всегда используйте результат: nums = append(nums, x)
//    - Помните о shared backing array между слайсами
//    - При необходимости возвращайте слайс из функции
//    - Или передавайте указатель на слайс: *[]int
