package main

import (
	"fmt"
	"unsafe"
)

func main() {
	// Демонстрация конвертации []byte в string без аллокаций

	byteSlice := []byte("hello world")

	// Стандартный способ: создает копию данных (аллокация)
	str1 := string(byteSlice)
	fmt.Println("Стандартный способ:", str1)

	// Способ через unsafe.Pointer: без аллокаций, но ОПАСНЫЙ
	str2 := *(*string)(unsafe.Pointer(&byteSlice))
	fmt.Println("Через unsafe:", str2)

	// ВАЖНО: изменение исходного слайса влияет на строку!
	byteSlice[0] = 'H'
	fmt.Println("После изменения слайса:", str2) // Выведет: Hello world

	// Безопасная альтернатива через unsafe с копированием внутренней структуры
	str3 := unsafeByteSliceToString(byteSlice)
	fmt.Println("Безопасный unsafe:", str3)
}

// unsafeByteSliceToString конвертирует []byte в string без аллокаций.
//
// СМЫСЛ ОТДЕЛЬНОЙ ФУНКЦИИ:
// Выделение unsafe операции в отдельную функцию это best practice:
// 1. Изолирует опасный код в одном месте
// 2. Упрощает code review (видно где используется unsafe)
// 3. Позволяет добавить дополнительные проверки/логирование
// 4. Документирует контракт и риски использования
//
// ГДЕ ПРОИСХОДИТ КОНВЕРТАЦИЯ БЕЗ АЛЛОКАЦИИ:
// Конвертация происходит на уровне переинтерпретации типов в памяти.
// Go runtime НЕ вызывает:
// - malloc/new для выделения памяти
// - memcpy для копирования данных
// - Никаких syscall'ов
//
// Что происходит пошагово:
// 1. &b берет адрес переменной b (слайс в стеке)
// 2. unsafe.Pointer(&b) преобразует *[]byte в unsafe.Pointer
// 3. (*string)(...) переинтерпретирует указатель как *string
// 4. *(...) разыменовывает, копируя string header (16 байт) на стек
//
// ПОЧЕМУ ЭТО НЕБЕЗОПАСНО:
// Строка и слайс теперь указывают на ОДНИ И ТЕ ЖЕ данные в памяти:
//
//	Memory Layout:
//	┌─────────────────────┐
//	│  Data: "hello"      │ ← общие данные
//	└─────────────────────┘
//	      ↑         ↑
//	      │         │
//	 byteSlice   string
//	{ptr, 5, 5}  {ptr, 5}
//
// Риски:
// 1. Изменение слайса → изменится строка (нарушение immutability)
// 2. Если слайс переаллоцируется → string указывает на старую память
// 3. Если слайс освобождается GC → string указывает на мусор
// 4. Data race если горутины читают string и пишут в слайс
//
// ПОЧЕМУ unsafe.String (Go 1.20+) БЕЗОПАСНЕЕ:
// unsafe.String(ptr, len) создает строку из сырого указателя,
// но компилятор понимает намерение и может добавить проверки.
func unsafeByteSliceToString(b []byte) string {
	// Эта строка делает reinterpret_cast в терминах C++.
	// Никакой аллокации не происходит - только переинтерпретация типа.
	return *(*string)(unsafe.Pointer(&b))
}

// Ответ:
// *(*string)(unsafe.Pointer(&byte_slice))
//
// Объяснение:
//
// 1. Стандартный способ string([]byte) создает новую строку и копирует данные:
//    - Безопасно: строка независима от слайса
//    - Медленно: требует аллокации и копирования
//    - Рекомендуется в большинстве случаев
//
// 2. Способ через unsafe.Pointer:
//    - Быстро: нет аллокаций, нет копирования
//    - ОПАСНО: нарушает immutability строк
//    - Результат ссылается на те же данные в памяти
//    - Изменение слайса изменяет строку (undefined behavior!)
//
// 3. Внутреннее представление:
//    - []byte: {ptr *byte, len int, cap int}
//    - string: {ptr *byte, len int}
//    - Преобразование через unsafe просто отбрасывает поле cap
//
// 4. Когда использовать:
//    - ТОЛЬКО если вы уверены, что слайс не будет изменен
//    - В критичных по производительности участках
//    - При работе с read-only данными
//    - В библиотеках низкого уровня (runtime, reflect, encoding)
//
// 5. Альтернативы:
//    - strings.Builder — эффективное построение строк
//    - bytes.Buffer — буферизация с последующей конвертацией
//    - unsafe.String (Go 1.20+) — более явный способ
//
// Trade-offs:
// - Производительность vs безопасность
// - Стандартная конвертация: ~100ns для 1KB, но безопасна
// - unsafe конвертация: ~1ns, но может привести к багам и data races
//
